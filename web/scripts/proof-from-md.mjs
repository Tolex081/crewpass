// Generates src/proof-data-v2.ts from deploy/v2-live-run.md, so the proof page shows exactly the
// transactions the live run recorded (no hand-typed hashes).
//   node scripts/proof-from-md.mjs
import { readFileSync, writeFileSync } from "node:fs";

const md = readFileSync(new URL("../../deploy/v2-live-run.md", import.meta.url), "utf8");
const ran = md.match(/run (\d{4}-\d{2}-\d{2}T[\d:]+Z)/)?.[1] ?? "";
const rows = [];
for (const line of md.split("\n")) {
  const m = line.match(/^\| (\d+) \| ([^|]+) \| (.+) \| (ok|refused) \| ([^|]+) \| \[[^\]]*\]\(https:\/\/testnet\.nearblocks\.io\/txns\/([A-Za-z0-9]+)\) \|$/);
  if (!m) continue;
  const [, , who, action, expected, result, tx] = m;
  const refused = result.startsWith("refused");
  if ((expected === "ok") === refused) throw new Error(`row ${m[1]} did not match its expectation: ${result}`);
  rows.push({
    who: who.trim().replace(/^crewpass-/, ""),
    action: action.replace(/`/g, "").trim(),
    outcome: refused ? "refused" : "ok",
    ...(refused ? { detail: result.replace(/^refused: /, "").trim() } : {}),
    tx,
  });
}
if (rows.length === 0) throw new Error("no rows found");
const out = `// Generated by scripts/proof-from-md.mjs from deploy/v2-live-run.md (run ${ran}). Do not edit by hand.
import type { ProofRow } from "./proof-data";

export const v2RunAt = ${JSON.stringify(ran)};
export const v2Run: ProofRow[] = ${JSON.stringify(rows, null, 2)};
`;
writeFileSync(new URL("../src/proof-data-v2.ts", import.meta.url), out);
console.log(`wrote ${rows.length} rows`);
